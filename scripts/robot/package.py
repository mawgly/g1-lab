def span(values, fmt='{:.1f}'):
    """'a–b' over the values as formatted (one number when both ends print the same)."""
    values = list(values)
    a, b = fmt.format(min(values)), fmt.format(max(values))
    return a if a == b else f'{a}–{b}'


